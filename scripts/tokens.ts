// Generates src/styles/theme.css from design/tokens.json, the single source of
// the design tokens. Run it with `vp run tokens`.
import { readFileSync, writeFileSync } from "node:fs";
import { basename } from "node:path";
import * as z from "zod";

const Named = z.object({ name: z.string(), value: z.string() });

const TokensSchema = z.object({
  color: z.object({
    tokens: z.array(
      z.object({ name: z.string(), value: z.object({ light: z.string(), dark: z.string() }) }),
    ),
  }),
  type: z.object({
    fonts: z.array(z.object({ family: z.string(), file: z.string(), weight: z.string() })),
    families: z.object({ sans: z.string(), mono: z.string() }),
    groups: z.array(
      z.object({
        styles: z.array(
          z.object({
            name: z.string(),
            fontSize: z.string(),
            lineHeight: z.string(),
            fontWeight: z.number(),
            letterSpacing: z.string().optional(),
          }),
        ),
      }),
    ),
  }),
  spacing: z.object({ tokens: z.array(Named) }),
  radius: z.object({ tokens: z.array(Named) }),
  shadow: z.object({ tokens: z.array(Named) }),
  border: z.object({ tokens: z.array(Named) }),
});

const SPACING_UNIT = 4;

export function generateTheme(input: unknown): string {
  const tokens = TokensSchema.parse(input);
  const colors = tokens.color.tokens;

  // Values like "{accent-yellow}" point at another colour token.
  const resolve = (value: string, theme: "light" | "dark"): string => {
    const ref = /^\{(.+)\}$/.exec(value)?.[1];
    if (!ref) return value;
    const target = colors.find((c) => c.name === ref);
    if (!target) throw new Error(`Unknown colour reference ${value}`);
    return resolve(target.value[theme], theme);
  };

  for (const { name, value } of tokens.spacing.tokens) {
    const step = Number(name.replace("space-", ""));
    if (value !== `${step * SPACING_UNIT}px`) {
      throw new Error(`${name} is ${value}, expected ${step * SPACING_UNIT}px`);
    }
  }

  const light = colors.map((c) => `  --${c.name}: ${resolve(c.value.light, "light")};`);
  const dark = colors
    .filter((c) => resolve(c.value.dark, "dark") !== resolve(c.value.light, "light"))
    .map((c) => `  --${c.name}: ${resolve(c.value.dark, "dark")};`);
  const darkBlock = (selector: string, indent = "", extra: string[] = []) =>
    [`${selector} {`, "  color-scheme: dark;", ...dark, ...extra, "}"]
      .map((l) => indent + l)
      .join("\n");

  const fontFaces = tokens.type.fonts.map((f) =>
    [
      "@font-face {",
      `  font-family: "${f.family}";`,
      `  font-weight: ${f.weight};`,
      "  font-style: normal;",
      "  font-display: swap;",
      `  src: url("../assets/fonts/${basename(f.file)}") format("woff2");`,
      "}",
    ].join("\n"),
  );

  const textStyles = tokens.type.groups
    .flatMap((g) => g.styles)
    .flatMap((s) => [
      `  --text-${s.name}: ${s.fontSize};`,
      `  --text-${s.name}--line-height: ${s.lineHeight};`,
      `  --text-${s.name}--font-weight: ${s.fontWeight};`,
      ...(s.letterSpacing ? [`  --text-${s.name}--letter-spacing: ${s.letterSpacing};`] : []),
    ]);

  const theme = [
    "@theme inline {",
    "  --color-*: initial;",
    ...colors.map((c) => `  --color-${c.name}: var(--${c.name});`),
    "  --font-*: initial;",
    `  --font-sans: ${tokens.type.families.sans};`,
    `  --font-mono: ${tokens.type.families.mono};`,
    "  --text-*: initial;",
    ...textStyles,
    "  --radius-*: initial;",
    ...tokens.radius.tokens.map((r) => `  --${r.name}: ${r.value};`),
    "  --shadow-*: initial;",
    ...tokens.shadow.tokens.map(
      (s) => `  --${s.name}: ${s.value.replace(/#[0-9a-f]{6}$/i, "var(--line)")};`,
    ),
    `  --spacing: ${SPACING_UNIT}px;`,
    "}",
  ].join("\n");

  const borders = tokens.border.tokens.map(
    (b) => `@utility ${b.name} {\n  border-width: ${b.value};\n}`,
  );

  return (
    [
      "/* Generated by scripts/tokens.ts from design/tokens.json. Do not edit; run `vp run tokens`. */",
      ...fontFaces,
      [":root {", "  color-scheme: light;", ...light, "}"].join("\n"),
      darkBlock(':root[data-theme="dark"]'),
      `@media (prefers-color-scheme: dark) {\n${darkBlock(':root:not([data-theme="light"])', "  ")}\n}`,
      // Always-dark surfaces (console, ink bands) in either theme.
      darkBlock(".theme-dark", "", ["  color: var(--ink);"]),
      theme,
      ...borders,
    ].join("\n\n") + "\n"
  );
}

if (import.meta.main) {
  const tokens = JSON.parse(readFileSync("design/tokens.json", "utf8"));
  writeFileSync("src/styles/theme.css", generateTheme(tokens));
}
